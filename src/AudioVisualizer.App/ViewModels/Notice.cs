namespace AudioVisualizer.App.ViewModels;

/// <summary>
/// Сообщение для показа окном: и ошибка, и отчёт об успешной выгрузке.
/// </summary>
/// <remarks>
/// Ошибку в строку статуса не влезет - она обрезается многоточием, - поэтому она и приходит
/// сюда. Успехная выгрузка в строке помещается, но там её тоже легко пропустить.
/// </remarks>
/// <param name="Title">Заголовок по смыслу: «Не удалось выгрузить видео», «Выгрузка готова».</param>
/// <param name="Message">Подробности. У ошибки сюда же попадают слова ffmpeg и сама команда.</param>
/// <param name="FolderPath">
/// Папка с роликом для кнопки «открыть папку». У ошибки её нет: файла журнала больше не
/// остаётся, а ролик в ошибке не появился.
/// </param>
public sealed record Notice(string Title, string Message, string? FolderPath = null);