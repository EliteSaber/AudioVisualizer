using System.Windows;

namespace AudioVisualizer.App;

/// <summary>
/// Возвращает передний план окну-владельцу после закрытия дочернего окна.
/// </summary>
/// <remarks>
/// Windows возвращает передний план владельцу не всегда: при закрытии окна система
/// активирует следующее по Z-порядку, а это не обязательно владелец. Если за время жизни
/// дочернего окна передний план забрало другое приложение, после закрытия активируется
/// именно оно, и главное окно остаётся в тени. Владельца надо активировать явно.
///
/// Активировать надо после возврата из <c>ShowDialog</c>, а не в обработчике закрытия:
/// пока дочернее окно модальное, владелец выключен, и <c>SetForegroundWindow</c> на
/// выключенном окне не срабатывает. К моменту возврата из <c>ShowDialog</c> WPF включает
/// владельца снова.
///
/// Соседний проект TrainingLog делает то же самое (у него это «ловушка 9»). Отличия два:
/// здесь решение «активировать ли» отделено от самой активации, и его проверяют, и свёрнутое
/// окно возвращается в обычное состояние - свёрнутым главное окно активным не бывает.
/// </remarks>
internal static class OwnerActivation
{
    /// <summary>Возвращает передний план окну-владельцу.</summary>
    public static void Restore(Window? owner) => Restore(owner, static window => window.Activate());

    /// <summary>
    /// Возвращает передний план окну-владельцу, если владелец жив и показан.
    /// </summary>
    /// <param name="owner">Окно, которому возвращается передний план.</param>
    /// <param name="activate">Что именно активирует окно. Подменяется в проверках.</param>
    /// <remarks>
    /// У закрытого и неродившегося окна переднего плана нет, и активировать их бессмысленно.
    /// Поэтому решение вынесено отдельно от самой активации - его и проверяют.
    /// </remarks>
    internal static void Restore(Window? owner, Action<Window> activate)
    {
        ArgumentNullException.ThrowIfNull(activate);

        if (owner is not { IsVisible: true })
        {
            return;
        }

        // Свёрнутое окно активным не бывает: без возврата в обычное состояние
        // «главное окно стало активным» не выполнится.
        if (owner.WindowState == WindowState.Minimized)
        {
            owner.WindowState = WindowState.Normal;
        }

        activate(owner);
    }
}
